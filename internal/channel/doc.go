// Package channel - домен каналов без сети (EFR-1).
//
// Registry - справочник открытых каналов: выдает коды, держит лимит,
// находит канал по коду или id. Channel - комната на одну смену: рассаживает
// игроков по постам и опознает их по токену.
//
// Как они работают вместе:
//
//	создать:  r.Create(mode)  -> канал + токен хозяина
//	войти:    r.ByCode(code)  -> канал; ch.Join()       -> токен гостя
//	сокет:    r.ByID(id)      -> канал; ch.PostOf(tok)  -> пост
//	закрыть:  r.Remove(ch.ID())
//
// Замок реестра держится только на время работы с картами. Методы канала
// вызываются уже после него: медленный канал не тормозит остальные (ADR-002).
